const ARTIST_SET = new Set(LYRIC_ARTISTS);
const SOURCE_SET = new Set(LYRIC_SOURCES);

function normalize(source: string): string {
  return source.trim().replace(/\s+/g, " ").toLowerCase();
}

/** the source split into its credit parts: "a - b", "a, b", "a by b" */
function creditParts(source: string): string[] {
  return source
    .split(/\s+[-–—]\s+|,\s+|\s+by\s+/)
    .map((part) => part.trim())
    .filter((part) => part !== "");
}

export type LyricMatch = "keyword" | "artist" | "title" | null;

export function lyricMatch(source: string | undefined): LyricMatch {
  if (source === undefined) return null;
  const normalized = normalize(source);
  if (normalized === "") return null;
  if (
    !KEYWORD_EXCEPTIONS.includes(normalized) &&
    KEYWORD_PATTERNS.some((re) => re.test(normalized))
  ) {
    return "keyword";
  }
  if (SOURCE_SET.has(normalized)) return "title";
  const parts = creditParts(normalized);
  if (parts.length > 1 && parts.some((part) => ARTIST_SET.has(part))) {
    return "artist";
  }
  return null;
}

export function isCodeQuoteLanguage(language: string): boolean {
  return language.startsWith("code_") || language === "docker_file";
}

export function isSongLyricQuote(quote: QuoteLike, language: string): boolean {
  if (isCodeQuoteLanguage(language)) return false;
  return lyricMatch(quote.source) !== null;
}

/** drops song-lyric quotes; the remaining quote objects are untouched */
export function filterLyricQuotes<T extends QuoteLike>(
  quotes: readonly T[],
  language: string,
): T[] {
  return quotes.filter((quote) => !isSongLyricQuote(quote, language));
}
