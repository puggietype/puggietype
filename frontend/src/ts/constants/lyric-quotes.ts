/**
 * Song-lyric quote detection for the steam build (Legal & Trust ruling,
 * 2026-11-03). The quote data has no tags, so lyrics are found from the
 * `source` field only, with three rules (see docs/steam-asset-clearance.md):
 *
 * 1. keyword: the source says "lyrics", or credits a featured artist
 *    ("ft." / "feat."), the usual "Song, Artist ft. Artist" form;
 * 2. artist: the source names a recording artist from LYRIC_ARTISTS, as
 *    "Artist - Title", "Title - Artist", "Title, Artist" or "Title by Artist";
 * 3. title: the whole source (case-insensitive) is a song title from
 *    LYRIC_SOURCES, reviewed against the quote text (a source whose quotes
 *    read like a book or film line was left out).
 *
 * Code "languages" are never filtered. Matching is deliberately biased
 * toward dropping: a false positive only removes one quote from the steam
 * pool. The quote objects are never modified, so source fields stay intact.
 *
 * Kept free of runtime imports so vite.config.ts can use it at build time.
 */

